/**
 * Get course theme preset by ID
 */
export function getCourseThemePreset(id: string): CourseThemePreset | undefined {
  return courseThemePresets.find((preset) => preset.id === id);
}

/**
 * Get all course theme presets
 */
export function getAllCourseThemePresets(): CourseThemePreset[] {
  return courseThemePresets;
}

/**
 * Get course theme config by ID
 */
export function getCourseThemeConfig(id: string): CourseThemeConfig {
  const preset = getCourseThemePreset(id);
  return preset?.config ?? defaultCourseThemeConfig;
}
