#!/usr/bin/env bash
# Write deploy/compose/.env with random, local-only secrets (once; never overwrites a
# value, never prints one). Delete the file to regenerate. An existing file only gains
# the keys added since it was written.
#
# Nothing here is a provider key: Stripe, Razorpay, EVS and the AI endpoint are the local
# stubs, and AI authoring uses the offline engine. Tenants bring their own gateway
# accounts in the tenant admin (sealed with MTLMS_CREDENTIALS_ENCRYPTION_KEY).
set -euo pipefail
f="$(cd "$(dirname "$0")/.." && pwd)/deploy/compose/.env"
rand() { openssl rand -base64 64 | tr -d '/+=\n' | cut -c1-"$1"; }
umask 077

# key=generator pairs, in file order. The APIs want 32+ characters for every secret;
# INTERNAL_API_KEY is shared by the three APIs.
KEYS=(
  "MTLMS_JWT_SECRET=rand 64"
  "MTLMS_LEARNER_JWT_SECRET=rand 64"
  "MTLMS_CREDENTIALS_ENCRYPTION_KEY=rand 64"
  "MTLMS_INTERNAL_API_KEY=rand 48"
  "MTLMS_DEMO_PASSWORD=demo"
)

value() {
  case "$1" in
    demo) printf 'Demo-%s' "$(rand 12)" ;;
    rand*) rand "${1#rand }" ;;
  esac
}

if [[ ! -f "$f" ]]; then
  printf '# Generated by scripts/gen-local-env.sh. Local only; never commit.\n' >"$f"
  fresh=1
else
  fresh=0
fi

added=()
for entry in "${KEYS[@]}"; do
  key="${entry%%=*}"
  gen="${entry#*=}"
  if ! grep -q "^${key}=" "$f"; then
    printf '%s=%s\n' "$key" "$(value "$gen")" >>"$f"
    added+=("$key")
  fi
done

if ((fresh)); then
  echo "wrote deploy/compose/.env"
elif ((${#added[@]})); then
  echo "deploy/compose/.env: added ${added[*]}"
else
  echo "deploy/compose/.env exists (delete it to regenerate)"
fi
