// Mirrors getWizardPages in use-onboarding-wizard.ts. Same set of pages,
// same skipAI flags, guarantees parity with the pre-update flow.
function getAutoProvisionPages(
  homepageTemplateId: string,
): WizardPageDefinition[] {
  return [
    { slug: "home", title: "Home", templateId: homepageTemplateId, category: "home" },
    { slug: "about", title: "About Us", templateId: "about-us", category: "about" },
    { slug: "contact", title: "Contact Us", templateId: "contact-us", category: "contact" },
    { slug: "faq", title: "FAQ", templateId: "faq-us", category: "faq" },
    { slug: "privacy", title: "Privacy Policy", templateId: "privacy-us", category: "privacy" },
    { slug: "terms", title: "Terms of Service", templateId: "terms-us", category: "terms" },
    { slug: "login", title: "Login", templateId: "login-minimal", category: "login", skipAI: true },
    { slug: "profile", title: "Profile", templateId: "profile-minimal", category: "profile", skipAI: true },
  ];
}

// String the AI uses to ground its content in our org. Same shape used
// inside use-onboarding-wizard's buildWizardBusinessContext.
function buildBusinessContext(info: BusinessInfo): string {
  const parts: string[] = [];
  if (info.name) parts.push(`Organization: ${info.name}`);
  if (info.tagline) parts.push(`Tagline: ${info.tagline}`);
  if (info.description) parts.push(`About: ${info.description}`);
  if (info.contactEmail) parts.push(`Contact Email: ${info.contactEmail}`);
  if (info.industry) parts.push(`Industry: ${info.industry}`);
  if (info.founderName) parts.push(`Founder: ${info.founderName}`);
  return parts.join(". ");
}

async function withConcurrency<T>(
  tasks: (() => Promise<T>)[],
  maxConcurrent: number,
): Promise<PromiseSettledResult<T>[]> {
  const results: PromiseSettledResult<T>[] = new Array(tasks.length);
  let nextIndex = 0;

  async function worker() {
    while (nextIndex < tasks.length) {
      const i = nextIndex++;
      try {
        const value = await tasks[i]();
        results[i] = { status: "fulfilled", value };
      } catch (reason) {
        results[i] = { status: "rejected", reason };
      }
    }
  }

  const workers = Array.from(
    { length: Math.min(maxConcurrent, tasks.length) },
    () => worker(),
  );
  await Promise.all(workers);
  return results;
}

export type AutoProvisionPhase =
  | "idle"
  | "preparing"
  | "creating"
  | "ai-generating"
  | "publishing"
  | "saving-org"
  | "done"
  | "error";

export interface RunAutoProvisionInput {
  tenantId: string;
  templateId: string;
  themeId: string;
  businessInfo: BusinessInfo;
}

/**
 * Frontend orchestrator that takes over after the backend has provisioned
 * the tenant SHELL (tenant + plan + subdomain). Mirrors the rich
 * /dashboard/pages onboarding wizard's launch flow:
 *
 *   Phase 1 (creating)      → for every wizard page, createPage with template defaults
 *   Phase 2 (ai-generating) → per AI-eligible section, call pageAIService
 *                              .generateSection (max 3 concurrent), merge
 *                              into page, updatePage
 *   Phase 3 (publishing)    → togglePublish on every created page
 *   Phase 4 (certificate)   → select + publish a random certificate template
 *   Phase 5 (saving-org)    → persist BusinessInfo to tenant_org_details
 *
 * Result: the same per-section richness as the pre-update flow: About,
 * FAQ, Terms, Privacy, Contact, Home all generated by AI per their
 * registered SECTION_AI_CONFIGS schemas.
 */
export function useAutoProvisionAcademy() {
  const queryClient = useQueryClient();

  const [phase, setPhase] = useState<AutoProvisionPhase>("idle");
  const [pageProgresses, setPageProgresses] = useState<PageProgress[]>([]);
  const [error, setError] = useState<string | null>(null);
  const abortRef = useRef(false);

  const updateProgress = useCallback(
    (slug: string, patch: Partial<PageProgress>) => {
      setPageProgresses((prev) =>
        prev.map((p) => (p.slug === slug ? { ...p, ...patch } : p)),
      );
    },
    [],
  );

  const run = useCallback(
    async (input: RunAutoProvisionInput): Promise<boolean> => {
      const { tenantId, templateId, themeId, businessInfo } = input;
      abortRef.current = false;
      setError(null);

      // eslint-disable-next-line no-console
      console.log(
        "[auto-provision] run() called",
        { tenantId, templateId, themeId, hasBusinessInfo: !!businessInfo },
      );

      // Make every API call below scoped to the just-created tenant.
      // (axios interceptor reads selectedTenantId from useTenantStore.)
      useTenantStore.getState().selectTenant(tenantId);
      // eslint-disable-next-line no-console
      console.log("[auto-provision] selectTenant done, refetching /me…");

      // Refresh /me so the tenant store + UI know about the new tenant.
      // Awaited (not invalidate-and-forget), the next API call needs the
      // refreshed tenant context for owner permissions to resolve correctly.
      try {
        await queryClient.refetchQueries({ queryKey: authKeys.me() });
        // eslint-disable-next-line no-console
        console.log("[auto-provision] /me refetch resolved");
      } catch (err) {
        // eslint-disable-next-line no-console
        console.error("[auto-provision] /me refetch threw, continuing:", err);
        // Don't bail, the new membership exists in DB regardless. The next
        // tenant-scoped call will revalidate permissions on its own.
      }

      // Theme preset lookup with graceful fallback. The backend's
      // ALL_THEME_IDS enum (in admin-api's
      // src/lib/creator-intent/types.ts) is the closed list Gemini can
      // pick from, we MUST keep `getAllThemePresets()` in sync with that
      // enum, otherwise the wizard receives a theme id it can't render.
      // Even if drift sneaks in (it did once: "mindfulness" was declared
      // backend-side but missing from the frontend `themePresets` array),
      // we now degrade gracefully to "default" instead of bailing the
      // whole 5-phase page-creation pipeline.
      let themePreset = getThemePreset(themeId);
      if (!themePreset) {
        // eslint-disable-next-line no-console
        console.warn(
          `[auto-provision] themePreset "${themeId}" not in frontend registry, ` +
            `falling back to "default" so the wizard can continue. ` +
            `Add "${themeId}" to packages/ui-config/src/themes/palettes.ts.`,
        );
        themePreset =
          getThemePreset("default") ?? getAllThemePresets()[0];
        if (!themePreset) {
          // Catastrophic: zero theme presets available. Should be
          // impossible, at least "default" must exist, but guard
          // anyway rather than crash.
          // eslint-disable-next-line no-console
          console.error(
            "[auto-provision] no theme presets available, frontend misconfigured",
          );
          setPhase("error");
          setError("No theme presets available. Please contact support.");
          return false;
        }
      }
      // eslint-disable-next-line no-console
      console.log(
        `[auto-provision] themePreset resolved (requested="${themeId}", using="${themePreset.id}"), building wizard pages…`,
      );
      const theme: ThemeConfig = themePreset.config;

      // Same parity contract as the theme above: the backend's
      // ALL_TEMPLATE_IDS enum can name a homepage templateId that the
      // frontend's pageTemplates registry doesn't ship. If it does, fall
      // back to "basic" so the home page still gets created (with a
      // generic template) instead of failing only that page.
      let homepageTemplateId = templateId;
      if (!getTemplateById(homepageTemplateId)) {
        // eslint-disable-next-line no-console
        console.warn(
          `[auto-provision] homepage template "${templateId}" not in frontend registry, ` +
            `falling back to "basic". ` +
            `Add "${templateId}" to packages/lms-templates/src/page-templates.ts.`,
        );
        homepageTemplateId = "basic";
      }
      const wizardPages = getAutoProvisionPages(homepageTemplateId);

      setPageProgresses(
        wizardPages.map((wp) => ({
          slug: wp.slug,
          title: wp.title,
          status: "pending",
        })),
      );

      // Fetch tenant layout (header/footer/sidebar). For a brand-new
      // tenant, getLayoutWithHomepageLogo will likely return the default
      // we wrote during provisioning; on error, fall back to canonical
      // default (avoids blocking the launch on a transient failure).
      let layout: TenantLayout;
      try {
        layout = await getLayoutWithHomepageLogo(tenantId);
        // eslint-disable-next-line no-console
        console.log("[auto-provision] tenant layout fetched");
      } catch (err) {
        // eslint-disable-next-line no-console
        console.warn(
          "[auto-provision] getLayoutWithHomepageLogo failed, using default:",
          err,
        );
        layout = {
          ...getDefaultTenantLayout(tenantId),
          id: `layout-${tenantId}`,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
        } as TenantLayout;
      }

      // Available routes, used to filter footer-link sections so we don't
      // ship links to routes that won't exist. The /tenant/routes endpoint
      // reads X-Tenant-Id from the header (set above via selectTenant).
      let availableRoutes: AvailableRoutesResponse | null = null;
      try {
        availableRoutes = await routesApi.getAvailableRoutes();
        // eslint-disable-next-line no-console
        console.log("[auto-provision] available routes fetched");
      } catch (err) {
        // eslint-disable-next-line no-console
        console.warn(
          "[auto-provision] routesApi.getAvailableRoutes failed:",
          err,
        );
        availableRoutes = null;
      }

      // eslint-disable-next-line no-console
      console.log("[auto-provision] entering Phase 0 (cleanup) → preparing");
      setPhase("preparing");

      // Phase 0, defensive cleanup of any pre-existing pages with the
      // same slugs (shouldn't happen for a fresh tenant, but keep parity
      // with the rich wizard's resilience).
      try {
        const existing = await pagesApi.getPages(tenantId, 1, 200);
        const slugsToCreate = new Set(wizardPages.map((wp) => wp.slug));
        const conflicting = existing.pages.filter((p) =>
          slugsToCreate.has(p.slug),
        );
        // eslint-disable-next-line no-console
        console.log(
          `[auto-provision] Phase 0: ${existing.pages.length} existing pages, ${conflicting.length} conflicting`,
        );
        for (const page of conflicting) {
          await pagesApi.deletePage(page.id);
        }
      } catch (err) {
        // eslint-disable-next-line no-console
        console.warn(
          "[auto-provision] Phase 0 cleanup failed (non-fatal):",
          err,
        );
      }

      // ---------------------------------------------------------------
      // Phase 1, create pages with template defaults
      // ---------------------------------------------------------------
      // eslint-disable-next-line no-console
      console.log(
        `[auto-provision] entering Phase 1 (creating), ${wizardPages.length} pages to create`,
      );
      setPhase("creating");
      const created: {
        slug: string;
        pageId: string;
        sections: SectionConfig[];
        skipAI?: boolean;
      }[] = [];

      for (const wp of wizardPages) {
        if (abortRef.current) break;
        updateProgress(wp.slug, { status: "creating" });

        const template = getTemplateById(wp.templateId);
        if (!template) {
          updateProgress(wp.slug, {
            status: "error",
            error: `Template "${wp.templateId}" not found`,
          });
          continue;
        }

        const filteredSections = filterSectionsFooterLinksByAvailableRoutes(
          template.sections,
          availableRoutes,
        );
        const sectionsWithLayout = embedLayoutInSections(
          filteredSections,
          layout,
        );

        try {
          const page = await pagesApi.createPage({
            tenantId,
            slug: wp.slug,
            title: wp.title,
            sections: sectionsWithLayout,
            theme,
            seo: { ...template.seo, title: wp.title },
          });
          updateProgress(wp.slug, { status: "created", pageId: page.id });
          created.push({
            slug: wp.slug,
            pageId: page.id,
            sections: page.sections,
            skipAI: wp.skipAI,
          });
        } catch (err) {
          const errMsg = err instanceof Error ? err.message : String(err);
          updateProgress(wp.slug, { status: "error", error: errMsg });
        }
      }

      if (created.length === 0) {
        setPhase("error");
        setError("No pages could be created. Please try again.");
        return false;
      }

      // ---------------------------------------------------------------
      // Phase 2: AI generation per section, max 3 concurrent
      // ---------------------------------------------------------------
      setPhase("ai-generating");
      const businessContext = buildBusinessContext(businessInfo);

      const aiEligible = created.filter((p) => !p.skipAI);
      for (const p of created) {
        if (p.skipAI) updateProgress(p.slug, { status: "ai-done" });
      }

      const aiTasks = aiEligible.map(({ pageId, slug, sections }) => async () => {
        updateProgress(slug, { status: "ai-generating" });

        const pageLayout = sections
          .filter((s) => s.visible !== false)
          .map((s, i) => ({ type: s.type, order: s.order ?? i }));

        const generatable = sections.filter(
          (s) => s.type in SECTION_AI_CONFIGS,
        );
        if (generatable.length === 0) {
          updateProgress(slug, { status: "ai-done" });
          return;
        }

        const updatedSections = [...sections];
        let anyFailed = false;

        const results = await Promise.allSettled(
          generatable.map(async (section) => {
            const cfg = SECTION_AI_CONFIGS[section.type];
            if (!cfg) return;

            const result = await pageAIApi.generateSection({
              sectionType: section.type,
              prompt: businessInfo.description,
              businessContext,
              pageLayout,
              generateImages: AI_AUTO_IMAGES_ENABLED,
              clientSchema: cfg.jsonSchema,
              clientInstructions: cfg.instructions,
            });

            const content = cfg.transform(result.content, result.orgLogos);
            const idx = updatedSections.findIndex((s) => s.id === section.id);
            if (idx !== -1) {
              const existing = (updatedSections[idx].content ?? {}) as Record<
                string,
                unknown
              >;
              updatedSections[idx] = {
                ...updatedSections[idx],
                content: {
                  ...existing,
                  ...(content as Record<string, unknown>),
                },
              };
            }
          }),
        );

        anyFailed = results.some((r) => r.status === "rejected");

        try {
          await pagesApi.updatePage(pageId, { sections: updatedSections });
          updateProgress(slug, {
            status: anyFailed ? "ai-failed" : "ai-done",
          });
        } catch {
          updateProgress(slug, { status: "ai-failed" });
        }
      });

      await withConcurrency(aiTasks, 3);

      // ---------------------------------------------------------------
      // Phase 3, publish all pages
      //
      // Errors used to be silently swallowed by Promise.allSettled,
      // leaving pages stuck in DRAFT while the UI happily reported
      // "published". We now log every rejection and aggregate the
      // failures into a single user-visible error so the build screen
      // shows what actually shipped.
      // ---------------------------------------------------------------
      setPhase("publishing");
      const publishResults = await Promise.allSettled(
        created.map(async ({ slug, pageId }) => {
          updateProgress(slug, { status: "publishing" });
          try {
            await pagesApi.togglePublish(pageId, true);
            updateProgress(slug, { status: "published" });
            return { slug, ok: true as const };
          } catch (err) {
            const errMsg = err instanceof Error ? err.message : String(err);
            // eslint-disable-next-line no-console
            console.error(
              `[auto-provision] publish failed for slug=${slug} pageId=${pageId}:`,
              err,
            );
            updateProgress(slug, {
              status: "error",
              error: `Publish failed: ${errMsg}`,
            });
            return { slug, ok: false as const, errMsg };
          }
        }),
      );

      const failedPublishes = publishResults
        .map((r) => (r.status === "fulfilled" ? r.value : null))
        .filter((v): v is { slug: string; ok: false; errMsg: string } =>
          !!v && v.ok === false,
        );
      if (failedPublishes.length > 0) {
        const slugList = failedPublishes.map((f) => f.slug).join(", ");
        setError(
          `${failedPublishes.length} page(s) failed to publish (${slugList}). ` +
            `Open the dashboard to retry.`,
        );
      }

      // ---------------------------------------------------------------
      // Phase 4, pick + publish a random certificate template
      //
      // Mirrors the production wizard's launch flow at
      // use-onboarding-wizard.ts (Phase 4). Best-effort: a tenant without
      // a certificate template still has a usable academy.
      // ---------------------------------------------------------------
      try {
        const { templates } = await certificateTemplatesApi.getTemplates();
        const available = templates.filter((t) => t.available);
        if (available.length > 0) {
          const random = available[Math.floor(Math.random() * available.length)];
          await certificateTemplatesApi.selectTemplate(random.id);
          await certificateTemplatesApi.togglePublish(true);
        }
      } catch (err) {
        // eslint-disable-next-line no-console
        console.warn("[auto-provision] certificate template setup failed:", err);
      }

      // ---------------------------------------------------------------
      // Phase 5, persist BusinessInfo on tenant_org_details
      // ---------------------------------------------------------------
      setPhase("saving-org");
      try {
        const addr = businessInfo.address;
        const social = businessInfo.socialLinks;
        await tenantOrgApi.updateOrgDetails({
          tagline: businessInfo.tagline || null,
          description: businessInfo.description || null,
          contact_email: businessInfo.contactEmail || null,
          support_email: businessInfo.supportEmail || null,
          phone_numbers: businessInfo.phoneNumbers.filter(Boolean).length
            ? businessInfo.phoneNumbers.filter(Boolean)
            : null,
          whatsapp_numbers: businessInfo.whatsappNumbers.filter(Boolean).length
            ? businessInfo.whatsappNumbers.filter(Boolean)
            : null,
          address: addr.line1
            ? {
                line1: addr.line1 || undefined,
                line2: addr.line2 || undefined,
                city: addr.city || undefined,
                state: addr.state || undefined,
                country: addr.country || undefined,
                postalCode: addr.postalCode || undefined,
              }
            : null,
          founder_name: businessInfo.founderName || null,
          founder_title: businessInfo.founderTitle || null,
          founder_bio: businessInfo.founderBio || null,
          social_links: social.website
            ? {
                website: social.website || undefined,
                linkedin: social.linkedin || undefined,
                twitter: social.twitter || undefined,
                facebook: social.facebook || undefined,
                instagram: social.instagram || undefined,
                youtube: social.youtube || undefined,
              }
            : null,
          legal_entity_name: businessInfo.legalEntityName || null,
          registration_number: businessInfo.registrationNumber || null,
          year_established: businessInfo.yearEstablished
            ? parseInt(businessInfo.yearEstablished, 10)
            : null,
          industry: businessInfo.industry || null,
        });
      } catch {
        // Non-fatal, pages already shipped, dashboard remains usable.
      }

      queryClient.invalidateQueries({ queryKey: pageKeys.lists() });
      queryClient.invalidateQueries({ queryKey: availableRoutesKeys.all });
      queryClient.invalidateQueries({ queryKey: ["tenant-org"] });

      setPhase("done");
      return true;
    },
    [queryClient, updateProgress],
  );

  const reset = useCallback(() => {
    setPhase("idle");
    setPageProgresses([]);
    setError(null);
  }, []);

  return { phase, pageProgresses, error, run, reset };
}
