/**
 * Sync the backend's `TemplateId` / `ThemeId` union types and their
 * runtime arrays (`ALL_TEMPLATE_IDS`, `ALL_THEME_IDS`) from the
 * FRONTEND's source registries.
 *
 * Frontend = single source of truth:
 *   - Themes:    `themePresets` in
 *                `packages/ui-config/src/themes/palettes.ts`
 *   - Templates: `pageTemplates` in
 *                `packages/lms-templates/src/page-templates.ts`,
 *                filtered to entries with `pageCategories.includes("home")`
 *                (only homepage-eligible templates can be picked by the AI model
 *                in the auto-provisioning flow).
 *
 * The backend's `src/lib/creator-intent/types.ts` exposes four
 * declarations regenerated by this script:
 *   - `export type TemplateId = "..." | "..." | …;`
 *   - `export type ThemeId    = "..." | "..." | …;`
 *   - `export const ALL_TEMPLATE_IDS: TemplateId[] = […];`
 *   - `export const ALL_THEME_IDS:    ThemeId[]    = […];`
 *
 * Each block is fenced with marker comments so this script can replace
 * just that span without touching the hand-written code around it.
 *
 * Usage:
 *   pnpm sync:frontend-ids
 *
 * Run this any time you add or remove a theme / homepage template on
 * the frontend. Commit the resulting types.ts diff. There is no runtime
 * check, drift is prevented because the backend's lists are *generated*
 * from the frontend's source, not maintained by hand.
 */

import * as fs from "node:fs";
import * as path from "node:path";

const BACKEND_ROOT = path.resolve(__dirname, "..");
// Monorepo root: packages/ui-config etc. live there.
const FRONTEND_PORTAL_ROOT = path.resolve(BACKEND_ROOT, "..", "..");

const BACKEND_TYPES_FILE = path.join(
  BACKEND_ROOT,
  "src/lib/creator-intent/types.ts",
);
const FRONTEND_THEMES_FILE = path.join(
  FRONTEND_PORTAL_ROOT,
  "packages/ui-config/src/themes/palettes.ts",
);
const FRONTEND_TEMPLATES_FILE = path.join(
  FRONTEND_PORTAL_ROOT,
  "packages/lms-templates/src/page-templates.ts",
);

// ─── helpers ─────────────────────────────────────────────────────────────

function readFile(p: string): string {
  if (!fs.existsSync(p)) {
    console.error(`✗ Missing file: ${p}`);
    process.exit(1);
  }
  return fs.readFileSync(p, "utf8");
}

/**
 * Pull the `[ ... ]` body of an array literal that follows a declaration
 * marker. Anchors on the `=` after the identifier so TypeScript type
 * annotations like `: ThemeId[]` don't trip the bracket finder.
 */
function extractArrayBlock(source: string, marker: RegExp): string | null {
  const m = source.match(marker);
  if (!m) return null;
  const eq = source.indexOf("=", m.index! + m[0].length);
  if (eq === -1) return null;
  const start = source.indexOf("[", eq);
  if (start === -1) return null;
  let depth = 0;
  for (let i = start; i < source.length; i++) {
    const ch = source[i];
    if (ch === "[") depth++;
    else if (ch === "]") {
      depth--;
      if (depth === 0) return source.slice(start + 1, i);
    }
  }
  return null;
}

/**
 * Pull the `id:` field of every TOP-LEVEL object literal inside an array
 * block. Critical to track brace depth, each ThemePreset has both a
 * top-level `id` and a nested `config.id`; a flat regex picks up both
 * and produces duplicates.
 */
function parseObjectIds(block: string): string[] {
  const ids: string[] = [];
  let depth = 0;
  let i = 0;
  while (i < block.length) {
    const ch = block[i];
    if (ch === "{") {
      depth++;
      // At depth 1 we're directly inside one of the array's entries.
      // Look for `id: "..."` somewhere in the immediate body of THIS
      // object (i.e., before the next `{` that would push us deeper).
      // Capture the first match at this depth, then keep scanning so
      // sub-objects' braces are still counted.
      if (depth === 1) {
        const idMatch = block.slice(i + 1).match(
          /^([^{}]*?)(?<![\w])id\s*:\s*["']([^"'\n]+)["']/,
        );
        if (idMatch) ids.push(idMatch[2]);
      }
      i++;
      continue;
    }
    if (ch === "}") {
      depth--;
    }
    i++;
  }
  return ids;
}

function parseIdentifierArray(block: string): string[] {
  return Array.from(
    block.matchAll(/(?<![\w])([a-zA-Z_$][\w$]*)\s*,?/g),
  ).map((m) => m[1]);
}

/**
 * Homepage templates whose `theme` field is NOT a `getThemePreset("id")`
 * call (they render on a named ThemeConfig import or `defaultThemeConfig`),
 * so the theme id can't be parsed from the source. Map them explicitly.
 * `code-tech` renders on `defaultThemeConfig` in the page template, but the
 * onboarding wizard has always paired it with the dark `shadcn-midnight`
 * preset, that pairing is preserved here.
 */
const OVERRIDE_THEME: Record<string, string> = {
  basic: "default",
  "code-tech": "shadcn-midnight",
  mindfulness: "mindfulness",
};

interface TemplateMeta {
  id: string;
  pageCategories: string[];
  name: string;
  description: string;
  themeId: string;
}

/**
 * For each named PageTemplate constant, locate its declaration and pull
 * out its `id`, `pageCategories`, `name`, `description` and paired theme
 * id (from `theme: getThemePreset("...")`, falling back to OVERRIDE_THEME).
 * Returns only entries we could parse, anything that fails is silently
 * skipped (the caller verifies the count later against an expected minimum).
 */
function resolveTemplateConstants(
  source: string,
  names: string[],
): TemplateMeta[] {
  const result: TemplateMeta[] = [];
  for (const name of names) {
    const re = new RegExp(
      `(?<![\\w])const\\s+${name}\\s*[:=]([\\s\\S]*?)(?=(?:\\n[a-z]|\\nexport|\\nconst\\s+\\w))`,
      "i",
    );
    const m = source.match(re);
    if (!m) continue;
    const body = m[1];
    const idMatch = body.match(/(?<![\w])id\s*:\s*["']([^"'\n]+)["']/);
    const pcMatch = body.match(
      /(?<![\w])pageCategories\s*:\s*\[([^\]]*)\]/,
    );
    if (!idMatch || !pcMatch) continue;
    const pageCategories = Array.from(
      pcMatch[1].matchAll(/["']([^"'\n]+)["']/g),
    ).map((mm) => mm[1]);
    const nameMatch = body.match(/(?<![\w])name\s*:\s*["']([^"'\n]+)["']/);
    const descMatch = body.match(
      /(?<![\w])description\s*:\s*["']([^"'\n]+)["']/,
    );
    const themeMatch = body.match(
      /(?<![\w])theme\s*:\s*getThemePreset\(\s*["']([^"'\n]+)["']/,
    );
    const id = idMatch[1];
    result.push({
      id,
      pageCategories,
      name: nameMatch?.[1] ?? id,
      description: descMatch?.[1] ?? "",
      themeId: themeMatch?.[1] ?? OVERRIDE_THEME[id] ?? "default",
    });
  }
  return result;
}

// ─── load frontend sources ───────────────────────────────────────────────

const themesSrc = readFile(FRONTEND_THEMES_FILE);
const templatesSrc = readFile(FRONTEND_TEMPLATES_FILE);

const frontendThemeBlock = extractArrayBlock(
  themesSrc,
  /export const themePresets\s*[:=]/,
);
const frontendTemplateBlock = extractArrayBlock(
  templatesSrc,
  /export const pageTemplates\s*[:=]/,
);

if (!frontendThemeBlock || !frontendTemplateBlock) {
  console.error(
    "✗ Could not locate `themePresets` and/or `pageTemplates` arrays " +
      "in the frontend source files. Verify file structure hasn't changed:",
  );
  console.error(`   ${FRONTEND_THEMES_FILE}`);
  console.error(`   ${FRONTEND_TEMPLATES_FILE}`);
  process.exit(1);
}

// Themes: inline objects with `id: "..."`
const themeIds = parseObjectIds(frontendThemeBlock);

// Templates: array of named constant references → resolve each name to
// its declaration → keep only entries with `pageCategories.includes("home")`
const templateRefs = parseIdentifierArray(frontendTemplateBlock);
const templateConstants = resolveTemplateConstants(templatesSrc, templateRefs);
const homeTemplates = templateConstants
  .filter((t) => t.pageCategories.includes("home"))
  .sort((a, b) => a.id.localeCompare(b.id));
const templateIds = homeTemplates.map((t) => t.id);

// Sanity gates, refuse to write empty/short lists. Catches the case
// where a regex change silently produces zero matches and would
// otherwise wipe out the backend's enums.
if (themeIds.length < 5) {
  console.error(
    `✗ Parsed only ${themeIds.length} theme ids, refusing to write. ` +
      `The frontend almost certainly has more; the regex broke. ` +
      `Aborting before clobbering the backend types.ts.`,
  );
  process.exit(1);
}
if (templateIds.length < 3) {
  console.error(
    `✗ Parsed only ${templateIds.length} homepage template ids, ` +
      `refusing to write. Aborting before clobbering the backend types.ts.`,
  );
  process.exit(1);
}

// Stable sort so re-running on the same frontend produces identical
// output, important for clean git diffs.
themeIds.sort();
templateIds.sort();

// Every template's recommended theme MUST be a real theme id, otherwise the
// generated TEMPLATE_CATALOG would carry a `recommendedThemeId` outside the
// `ThemeId` union and the backend type-check would fail. Catch it here with a
// clear message instead of a cryptic tsc error.
const themeIdSet = new Set(themeIds);
for (const t of homeTemplates) {
  if (!themeIdSet.has(t.themeId)) {
    console.error(
      `✗ Template "${t.id}" resolved theme "${t.themeId}", which is not a known ` +
        `theme id. Add the theme to themePresets, or map it in OVERRIDE_THEME ` +
        `in this script. Aborting before writing.`,
    );
    process.exit(1);
  }
}

// ─── render the new types.ts blocks ──────────────────────────────────────

const indent = "  ";

function renderUnionType(
  exportName: string,
  ids: string[],
): string {
  return [
    `export type ${exportName} =`,
    ...ids.map(
      (id, i) => `${indent}| "${id}"${i === ids.length - 1 ? ";" : ""}`,
    ),
  ].join("\n");
}

function renderArrayConst(
  exportName: string,
  typeName: string,
  ids: string[],
): string {
  return [
    `export const ${exportName}: ${typeName}[] = [`,
    ...ids.map((id) => `${indent}"${id}",`),
    `];`,
  ].join("\n");
}

/**
 * Render the TEMPLATE_CATALOG, the id/name/description/theme metadata the
 * onboarding the AI model picker uses to choose accurately across ALL homepage
 * templates. Descriptions are the frontend's own copy, so this stays the
 * single source of truth and never drifts.
 */
function renderCatalog(entries: TemplateMeta[]): string {
  return [
    "export interface TemplateCatalogEntry {",
    `${indent}id: TemplateId;`,
    `${indent}name: string;`,
    `${indent}description: string;`,
    `${indent}recommendedThemeId: ThemeId;`,
    "}",
    "",
    "export const TEMPLATE_CATALOG: TemplateCatalogEntry[] = [",
    ...entries.map(
      (t) =>
        `${indent}{ id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(
          t.name,
        )}, description: ${JSON.stringify(
          t.description,
        )}, recommendedThemeId: ${JSON.stringify(t.themeId)} },`,
    ),
    "];",
  ].join("\n");
}

const newTemplateIdType = renderUnionType("TemplateId", templateIds);
const newThemeIdType = renderUnionType("ThemeId", themeIds);
const newAllTemplateIds = renderArrayConst(
  "ALL_TEMPLATE_IDS",
  "TemplateId",
  templateIds,
);
const newAllThemeIds = renderArrayConst(
  "ALL_THEME_IDS",
  "ThemeId",
  themeIds,
);
const newTemplateCatalog = renderCatalog(homeTemplates);

// ─── splice into types.ts between marker fences ──────────────────────────

const BEGIN = "// AUTO-GENERATED:BEGIN frontend-ids, do NOT edit by hand";
const END = "// AUTO-GENERATED:END frontend-ids";

const generatedBlock = [
  BEGIN,
  "// Regenerated by `pnpm sync:frontend-ids` from the frontend source.",
  "// Source files (frontend = canonical):",
  "//   themePresets, packages/ui-config/src/themes/palettes.ts",
  "//   pageTemplates, packages/lms-templates/src/page-templates.ts",
  "//                   (filtered to entries with pageCategories: ['home'])",
  "",
  newTemplateIdType,
  "",
  newThemeIdType,
  "",
  newAllTemplateIds,
  "",
  newAllThemeIds,
  "",
  newTemplateCatalog,
  END,
].join("\n");

let backendSrc = readFile(BACKEND_TYPES_FILE);

if (backendSrc.includes(BEGIN) && backendSrc.includes(END)) {
  // Replace existing fenced block.
  const re = new RegExp(
    `${BEGIN.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&")}[\\s\\S]*?${END.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&")}`,
  );
  backendSrc = backendSrc.replace(re, generatedBlock);
} else {
  // First run, strip the legacy hand-written declarations and replace
  // with the fenced block. We match each of the four declarations by
  // name and remove them, then append the generated block at the end of
  // the file (developer can move it where they want on first commit).
  for (const decl of [
    /^\/\*\*[\s\S]*?FRONTEND-PARITY CONTRACT[\s\S]*?\*\/\s*\n/m,
    /^export type TemplateId =[\s\S]*?;\s*\n/m,
    /^export type ThemeId =[\s\S]*?;\s*\n/m,
    /^export const ALL_TEMPLATE_IDS[\s\S]*?\];\s*\n/m,
    /^export const ALL_THEME_IDS[\s\S]*?\];\s*\n/m,
  ]) {
    backendSrc = backendSrc.replace(decl, "");
  }
  backendSrc = backendSrc.trimEnd() + "\n\n" + generatedBlock + "\n";
}

fs.writeFileSync(BACKEND_TYPES_FILE, backendSrc, "utf8");

console.log(`✓ Synced backend enums from frontend source`);
console.log(`  themes:    ${themeIds.length} ids`);
console.log(`  templates: ${templateIds.length} homepage-eligible ids`);
console.log(`  catalog:   ${homeTemplates.length} entries (name + description + theme)`);
console.log(`  → ${path.relative(process.cwd(), BACKEND_TYPES_FILE)}`);
console.log("");
console.log("Run `pnpm type-check` to confirm the new union types compile.");
