/**
 * The colour family a palette belongs to, derived from its own primary hue
 * rather than hand-tagged, so it cannot drift when the portal ships a new
 * preset. "Make my site bluish" is answered by filtering on this.
 */
export type PaletteFamily =
  | "red"
  | "orange"
  | "gold"
  | "green"
  | "teal"
  | "blue"
  | "violet"
  | "pink"
  | "neutral";

/** Hue and saturation from either an HSL triplet ("221 83% 53%") or a hex. */
function hueAndSaturation(colour: string): { hue: number; saturation: number } | null {
  const trimmed = colour.trim();

  const hsl = /^(-?[\d.]+)\s+([\d.]+)%\s+([\d.]+)%$/.exec(trimmed);
  if (hsl) return { hue: Number(hsl[1]), saturation: Number(hsl[2]) };

  const hex = /^#?([0-9a-f]{6})$/i.exec(trimmed);
  if (!hex) return null;
  const int = parseInt(hex[1]!, 16);
  const r = ((int >> 16) & 255) / 255;
  const g = ((int >> 8) & 255) / 255;
  const b = (int & 255) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const delta = max - min;
  const lightness = (max + min) / 2;
  if (delta === 0) return { hue: 0, saturation: 0 };
  const saturation = delta / (1 - Math.abs(2 * lightness - 1));
  let hue: number;
  if (max === r) hue = 60 * (((g - b) / delta) % 6);
  else if (max === g) hue = 60 * ((b - r) / delta + 2);
  else hue = 60 * ((r - g) / delta + 4);
  return { hue: (hue + 360) % 360, saturation: saturation * 100 };
}

export function familyOf(colour: string | undefined): PaletteFamily {
  const parsed = colour ? hueAndSaturation(colour) : null;
  if (!parsed || parsed.saturation < 12) return "neutral";
  const h = ((parsed.hue % 360) + 360) % 360;
  if (h < 15 || h >= 345) return "red";
  if (h < 45) return "orange";
  if (h < 70) return "gold";
  if (h < 160) return "green";
  if (h < 200) return "teal";
  if (h < 260) return "blue";
  if (h < 290) return "violet";
  return "pink";
}

function colours(config: Record<string, unknown>): {
  lightPrimary?: string;
  darkBackground?: string;
  lightBackground?: string;
} {
  const c = (config.colors ?? {}) as Record<string, Record<string, string> | undefined>;
  return {
    lightPrimary: c.light?.primary,
    lightBackground: c.light?.background,
    darkBackground: c.dark?.background,
  };
}

export interface PaletteSummary {
  id: string;
  name: string;
  description: string;
  /** Family of the BRAND colour: what the buttons and links look like. */
  family: PaletteFamily;
  /**
   * Family of the DARK-MODE CANVAS, which is a different question and the one
   * people usually mean by "make the dark theme blue". Most palettes pair a
   * coloured brand with a near-black canvas, so `family: "blue"` with
   * `darkFamily: "neutral"` is the common case, not a contradiction.
   */
  darkFamily: PaletteFamily;
  /** True when the dark canvas is actually tinted rather than near-black. */
  darkIsTinted: boolean;
  /** The brand colour in light mode, as stored (HSL triplet). */
  lightPrimary?: string;
  /** The page background in DARK mode. This is what a viewer sees at night. */
  darkBackground?: string;
}

/**
 * Every palette, with the family derived from its own primary.
 *
 * Deliberately lean: an admin chooses a palette by name and colour family, and
 * the full ThemeConfig (22 light values plus the dark block) is not something
 * anyone reads in a list.
 */
export function listPalettes(): PaletteSummary[] {
  return Object.values(THEMES).map((t) => {
    const { lightPrimary, darkBackground } = colours(t.config);
    const darkFamily = familyOf(darkBackground);
    return {
      id: t.id,
      name: t.name,
      description: t.description,
      family: familyOf(lightPrimary ?? t.preview?.primary),
      darkFamily,
      darkIsTinted: darkFamily !== "neutral",
      lightPrimary,
      darkBackground,
    };
  });
}

/**
 * The id of the theme a page is wearing.
 *
 * Deliberately NOT restricted to this catalogue. Most existing sites are on a
 * theme that predates it (`ocean-blue`, `royal-purple`, `midnight-dark`,
 * `emerald-green` come from the course-theme set), and returning undefined for
 * those made the assistant answer "you are not using any palette" to a site
 * that plainly has one. Reporting is about what IS; only applying is restricted
 * to the catalogue, which `applyPalette` enforces by refusing an unknown id.
 */
export function paletteIdOf(theme: unknown): string | undefined {
  if (!theme || typeof theme !== "object") return undefined;
  const id = (theme as { id?: unknown }).id;
  return typeof id === "string" && id.trim() ? id : undefined;
}

/**
 * The name to show for a stored theme: this catalogue's name where it knows
 * one, otherwise the name the theme carries itself, so a site on an older
 * theme is still described by its name rather than its id.
 */
export function paletteNameOf(theme: unknown): string | undefined {
  const id = paletteIdOf(theme);
  const known = id ? THEMES[id]?.name : undefined;
  if (known) return known;
  const own = (theme as { name?: unknown } | undefined)?.name;
  return typeof own === "string" && own.trim() ? own : undefined;
}
