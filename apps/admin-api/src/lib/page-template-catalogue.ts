/**
 * The page-template library, mirrored server-side.
 *
 * WHY A MIRROR
 * ------------
 * The real library lives in the admin portal (`@open-mtlms/lms-templates` and
 * `@open-mtlms/ui-config`) because that is where the editor renders it. The backend
 * does not, and should not, depend on the portal. But that split meant
 * choosing a website template was something only a person clicking in a browser
 * could do: there was no route to apply one, so a tenant asking the assistant
 * to "pick a proper template for a coding academy and put it live" had no path
 * to an answer beyond hand-writing sections one at a time.
 *
 * `src/data/page-template-catalogue.json` is a build artifact of the portal
 * packages, regenerated by `scripts/gen-page-template-catalogue.cjs`. It is
 * checked in deliberately: it is data, it is ~290KB, and pinning it means a
 * portal release cannot silently change what the assistant applies.
 *
 * WHEN THE PORTAL LIBRARY CHANGES, re-run the generator. A template the
 * catalogue does not know about simply cannot be applied, the route rejects an
 * unknown id rather than inventing sections, so drift shows up as a clean
 * "I don't have that template" rather than a broken page.
 */
import catalogue from "../data/page-template-catalogue.json";

export interface CatalogueSection {
  type: string;
  variant: string;
  order: number;
  content: Record<string, unknown>;
}

export interface CataloguePageTemplate {
  id: string;
  name: string;
  description: string;
  thumbnail: string;
  sections: CatalogueSection[];
}

export interface CatalogueTheme {
  id: string;
  name: string;
  description: string;
  preview: { primary?: string; secondary?: string; accent?: string } | null;
  /**
   * The full ThemeConfig. This is what gets written to a page's `theme` field.
   * and because the web app reads the HOMEPAGE's theme as the global site
   * theme, writing it there re-themes every page on the tenant's site.
   */
  config: Record<string, unknown>;
}

const TEMPLATES: CataloguePageTemplate[] = (
  catalogue as { templates: CataloguePageTemplate[] }
).templates;

/** Sign-in, profile and company pages: applied by id, never listed in the picker. */
const UTILITY_TEMPLATES: CataloguePageTemplate[] =
  (catalogue as { utilityTemplates?: CataloguePageTemplate[] }).utilityTemplates ?? [];

const THEMES: Record<string, CatalogueTheme> = (
  catalogue as { themes: Record<string, CatalogueTheme> }
).themes;

/**
 * The list a caller needs in order to CHOOSE. Deliberately lean.
 *
 * The first version returned each template's full section-type list and its
 * thumbnail URL as well: 51 templates x ~9 section types came to ~7,700 tokens,
 * which overflowed the assistant's read budget. It saw a truncated catalogue,
 * and then told the tenant a template did not exist when it did, a confident
 * wrong answer, which is worse than a slow one.
 *
 * Name, description and section count are what a choice is actually made on.
 * `describePageTemplate` returns the detail for one template when it is wanted.
 */
export function listPageTemplates(): Array<{
  id: string;
  name: string;
  description: string;
  sectionCount: number;
}> {
  return TEMPLATES.map((t) => ({
    id: t.id,
    name: t.name,
    description: t.description,
    sectionCount: t.sections.length,
  }));
}

/**
 * Rank templates against a description of the business, in words.
 *
 * The full list does not fit in what the assistant can read in one step
 * (3,000 characters), and a truncated catalogue produced the worst possible
 * outcome: it read the first ten of fifty-one and told the tenant a template
 * did not exist. So the caller says what the business IS, and gets back the
 * handful that match plus an honest total.
 *
 * The scoring is deliberately dumb and legible, word overlap against the id,
 * name and description. A smarter ranker would be harder to predict, and the
 * point here is that the same question gives the same answer every time.
 *
 * ORDER IS MEANING HERE, NOT PRESENTATION.
 * ----------------------------------------
 * A plan cannot name a template it has not looked up yet, so it refers to the
 * winner positionally: `$s1.templates.0.id`. Position 0 is therefore a DECISION
 * this function makes on the caller's behalf, and it has to be the best match
 * rather than merely the first.
 *
 * It was not. Asked for "technology and coding academy offering self-paced
 * courses, live bootcamps, books, and bundles", Astrology and Code & Technology
 * both scored 5: Astrology from "self", "paced", "courses", "live", "books",
 * Code & Technology from "technology", "coding", "courses", "bootcamps", and
 * the alphabetical tiebreak handed it to Astrology. A coding academy's homepage
 * was replaced with a cosmic celestial landing page.
 *
 * The flaw is that every template in an LMS catalogue says "courses", "books"
 * and "live", so those words carry no information, while "coding" and
 * "astrology" carry almost all of it. Weighting each word by how RARE it is
 * across the catalogue fixes that without making the ranker unpredictable: it
 * is still pure word overlap, still deterministic, still explainable in a
 * sentence. A word in most templates barely counts; a word in two counts a lot.
 */
/**
 * HOW MANY MATCHED, AND HOW MANY WE ARE SHOWING, ARE DIFFERENT NUMBERS.
 *
 * The caller used to get only the trimmed list, and the note built from it read
 * "8 of 51 templates matched", where 8 was the display cap, not the count.
 * Eleven templates matched the query that replaced a real homepage. Both the
 * owner and the model were told the catalogue offered fewer fits than it did,
 * which is the same shape of untruth as a truncated list being read as the
 * whole world.
 *
 * The limit itself was also tighter than it needed to be: eleven results
 * serialise to under 2,000 characters against a 3,000 character per-step
 * budget, so twelve fits comfortably where eight was leaving good matches out
 * for no reason.
 */
export function rankPageTemplates(query: string, limit = 12) {
  const all = scorePageTemplates(query);
  return {
    matches: all.slice(0, limit).map((x) => ({
      id: x.t.id,
      name: x.t.name,
      description: x.t.description,
      sectionCount: x.t.sections.length,
    })),
    /** Everything that scored, before the cap. */
    totalMatched: all.length,
  };
}

export function searchPageTemplates(query: string, limit = 12) {
  return rankPageTemplates(query, limit).matches;
}

function scorePageTemplates(query: string) {
  const words = query
    .toLowerCase()
    .split(/[^a-z0-9+#]+/)
    .filter((w) => w.length > 2 && !STOP_WORDS.has(w));

  return TEMPLATES.map((t) => {
    const hay = `${t.id} ${t.name} ${t.description}`.toLowerCase();
    let score = 0;
    for (const w of words) {
      const weight = rarityOf(w);
      if (t.id.toLowerCase().includes(w)) score += 3 * weight;
      else if (t.name.toLowerCase().includes(w)) score += 2 * weight;
      else if (hay.includes(w)) score += 1 * weight;
    }
    return { t, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || a.t.id.localeCompare(b.t.id));
}

/**
 * How much one word should count, given how many templates already use it.
 *
 * Plain inverse document frequency, computed once from the catalogue itself so
 * it stays correct as templates are added. A word in every template scores
 * ~0.02; a word in one of fifty-one scores ~1. Nothing is hard-coded, which
 * matters because the generic words are not knowable in advance: they are
 * whatever this catalogue happens to have in common.
 *
 * Substring containment, matching how the scorer tests words, so "coding"
 * counts the template whose description says "bootcamps for coding".
 */
let rarityCache: Map<string, number> | null = null;

function rarityOf(word: string): number {
  if (!rarityCache) rarityCache = new Map();
  const cached = rarityCache.get(word);
  if (cached !== undefined) return cached;

  let seenIn = 0;
  for (const t of TEMPLATES) {
    if (`${t.id} ${t.name} ${t.description}`.toLowerCase().includes(word)) seenIn++;
  }
  // log(N / df) normalised to roughly 0..1. A word in no template can still be
  // asked about; it simply matches nothing, so its weight never gets used.
  const weight = seenIn === 0 ? 1 : Math.log(TEMPLATES.length / seenIn) / Math.log(TEMPLATES.length);
  rarityCache.set(word, weight);
  return weight;
}

const STOP_WORDS = new Set([
  "the","and","for","with","our","site","website","page","design","template",
  "look","best","good","better","suit","suits","business","company","platform",
  "academy","from","that","this","have","need","want","would","like","them",
]);

/** Everything about one template, for when a caller wants to look before applying. */
export function describePageTemplate(id: string) {
  const t = getPageTemplate(id);
  if (!t) return undefined;
  return {
    id: t.id,
    name: t.name,
    description: t.description,
    thumbnail: t.thumbnail,
    sectionCount: t.sections.length,
    sectionTypes: t.sections.map((s) => s.type),
  };
}

export function getPageTemplate(id: string): CataloguePageTemplate | undefined {
  return TEMPLATES.find((t) => t.id === id) ?? UTILITY_TEMPLATES.find((t) => t.id === id);
}

export function listThemes(): CatalogueTheme[] {
  return Object.values(THEMES);
}

export function getTheme(id: string): CatalogueTheme | undefined {
  return THEMES[id];
}

export function templateIds(): string[] {
  return TEMPLATES.map((t) => t.id);
}

export function themeIds(): string[] {
  return Object.keys(THEMES);
}

